export function Icon({ name, className = 'h-5 w-5' }: { name: string; className?: string }) {
  const Glyph = icons[name] || PenLine
  return <Glyph className={`${className} shrink-0`} strokeWidth={1.75} aria-hidden="true" />
}

export function Mark({ className = 'h-10 w-10' }: { className?: string }) {
  return (
    <span className={`grid place-items-center rounded-2xl bg-[var(--accent)] text-[var(--accent-ink)] ${className}`}>
      <Icon name="pen" className="h-5 w-5" />
    </span>
  )
}
